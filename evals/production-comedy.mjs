export const DIRECTION_VARIANTS = Object.freeze({
  baseline: "Open with a joke, not context. Target 60 to 72 words and cut every sentence that merely explains the product.",
  "one-premise": "Use one supported premise only. Build three fresh turns from it and end on a clean final callback. Do not list repository facts.",
  "discourse-compression": "Open on the recurring public reputation or discourse from the brief. Compress the thread into one sharp line, then prove it with one supported contradiction.",
  "hard-callback": "Write exactly four sentences. Sentence one is a cold-open joke. Each later sentence must change the angle. Sentence four calls back to sentence one and stops on the punch.",
  "viewer-first": "Use one supported technical detail that a non-engineer can follow. State the contradiction plainly, with no hedge, scene-setting, or explanatory closer.",
});

function compatibleUrl(baseUrl) {
  const clean = String(baseUrl || "").trim().replace(/\/$/, "");
  if (!clean) throw new Error("--base-url is required for --provider openai-compatible.");
  return `${clean}/chat/completions`;
}

export function createCompatibleChat({ baseUrl, model, apiKey = "local", timeoutMs = 90_000, fetchImpl = fetch }) {
  const endpoint = compatibleUrl(baseUrl);
  const selectedModel = String(model || "").trim();
  if (!selectedModel) throw new Error("--model is required for --provider openai-compatible.");
  return async ({ system, user }) => {
    const response = await fetchImpl(endpoint, {
      method: "POST",
      headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
      body: JSON.stringify({ model: selectedModel, messages: [{ role: "system", content: system }, { role: "user", content: user }], temperature: 0.8, max_tokens: 320 }),
      signal: AbortSignal.timeout(timeoutMs),
    });
    if (!response.ok) {
      const detail = (await response.text().catch(() => "")).slice(0, 500);
      throw new Error(`OpenAI-compatible generation failed (${response.status}): ${detail || response.statusText}`);
    }
    const payload = await response.json();
    const text = payload?.choices?.[0]?.message?.content;
    if (!String(text || "").trim()) throw new Error("OpenAI-compatible model returned no text.");
    return String(text).trim();
  };
}

function candidateLabel(index) {
  let value = index + 1;
  let label = "";
  while (value > 0) {
    value -= 1;
    label = String.fromCharCode(65 + (value % 26)) + label;
    value = Math.floor(value / 26);
  }
  return label;
}

function wordCount(value) {
  return String(value || "").trim().split(/\s+/).filter(Boolean).length;
}

export function productionBlindReviewMarkdown(candidates) {
  const rows = [
    "# Production comedy baseline — blind review",
    "",
    "Every candidate was generated by the production `generateComedyScript` path. Model, prompt-direction, and cycle labels are hidden. Rank by whether this would make a good short roast video, not by technical detail density.",
    "",
  ];
  for (const [index, candidate] of candidates.entries()) {
    rows.push(`## Candidate ${candidateLabel(index)}`, "", candidate.script, "");
  }
  return `${rows.join("\n").trim()}\n`;
}

function parseArgs(args) {
  const options = { kind: "repository", templateId: "roast", cycles: 1, directions: Object.keys(DIRECTION_VARIANTS), outputRoot: "data/production-comedy-runs", provider: "production", baseUrl: "", model: "", apiKeyEnv: "", timeoutMs: 90_000 };
  for (let index = 0; index < args.length; index += 1) {
    const value = args[index];
    const next = () => args[++index] || "";
    if (value === "--subject") options.subjectUrl = next();
    else if (value === "--kind") options.kind = next();
    else if (value === "--template") options.templateId = next();
    else if (value === "--cycles") options.cycles = Math.min(Math.max(Number(next()) || 3, 1), 10);
    else if (value === "--directions") options.directions = next().split(",").filter(Boolean);
    else if (value === "--provider") options.provider = next();
    else if (value === "--base-url") options.baseUrl = next();
    else if (value === "--model") options.model = next();
    else if (value === "--api-key-env") options.apiKeyEnv = next();
    else if (value === "--timeout-ms") options.timeoutMs = Math.min(Math.max(Number(next()) || 90_000, 5_000), 120_000);
    else if (value === "--out") options.outputRoot = next();
    else if (value === "--help") options.help = true;
    else throw new Error(`Unknown argument: ${value}`);
  }
  if (!options.subjectUrl && !options.help) throw new Error("Usage: npm run evals:production -- --subject https://github.com/owner/repo [--cycles 3]");
  if (options.directions.some((key) => !(key in DIRECTION_VARIANTS))) {
    throw new Error(`--directions must use: ${Object.keys(DIRECTION_VARIANTS).join(", ")}`);
  }
  if (!["repository", "product"].includes(options.kind)) throw new Error("--kind must be repository or product.");
  if (!["production", "openai-compatible"].includes(options.provider)) throw new Error("--provider must be production or openai-compatible.");
  if (options.provider === "openai-compatible") {
    compatibleUrl(options.baseUrl);
    if (!options.model) throw new Error("--model is required for --provider openai-compatible.");
    if (options.apiKeyEnv && !process.env[options.apiKeyEnv]?.trim()) throw new Error(`--api-key-env ${options.apiKeyEnv} is missing from the environment.`);
  }
  return options;
}

async function productionResearch(kind, subjectUrl) {
  const summary = await researchSubject(kind, subjectUrl);
  const officialContext = await searchOfficialSocialContext(summary).catch((error) => ({
    answer: "",
    results: [],
    mode: "direct-public-data",
    warning: error instanceof Error ? error.message : "Official social research unavailable.",
  }));
  let publicContext;
  try {
    publicContext = await searchPublicContext(summary);
  } catch (error) {
      publicContext = { answer: "", results: [], mode: "direct-public-data", warning: error instanceof Error ? error.message : "Public research unavailable." };
  }
  const results = [...officialContext.results, ...publicContext.results];
  publicContext = {
    ...publicContext,
    results: results.filter((source, index) => source.url && results.findIndex((candidate) => candidate.url === source.url) === index),
    mode: officialContext.results.length ? `${officialContext.mode}+${publicContext.mode}` : publicContext.mode,
    warning: [officialContext.warning, publicContext.warning].filter(Boolean).join(" "),
  };
  try {
    const researchBrief = await synthesizeResearchBrief(summary, publicContext);
    return { summary, researchBrief, researchMode: `${publicContext.mode}+gpt-5.6-luna-synthesis`, researchWarning: publicContext.warning };
  } catch (error) {
    return {
      summary,
      researchBrief: buildResearchBrief(summary, publicContext),
      researchMode: publicContext.mode,
      researchWarning: [publicContext.warning, error instanceof Error ? error.message : ""].filter(Boolean).join(" "),
    };
  }
}

export async function runProductionComedyBaseline(options, dependencies = {}) {
  const research = await (dependencies.productionResearch || productionResearch)(options.kind, options.subjectUrl);
  const generate = dependencies.generateComedyScript || generateComedyScript;
  const chat = options.provider === "openai-compatible"
    ? (dependencies.createCompatibleChat || createCompatibleChat)({ baseUrl: options.baseUrl, model: options.model, apiKey: options.apiKeyEnv ? process.env[options.apiKeyEnv].trim() : "local", timeoutMs: options.timeoutMs, fetchImpl: dependencies.fetchImpl || fetch })
    : null;
  const provider = options.provider || "production";
  const model = provider === "openai-compatible" ? options.model : "openai/gpt-5.6-luna";
  const candidates = [];
  for (const variant of options.directions) {
    for (let cycle = 1; cycle <= options.cycles; cycle += 1) {
      try {
        const input = {
          subjectName: research.summary.name,
          researchBrief: research.researchBrief,
          customInstructions: DIRECTION_VARIANTS[variant],
          templateId: options.templateId,
        };
        const output = chat ? await generate(input, chat) : await generate(input);
        const words = wordCount(output.script);
        candidates.push({
          runId: `${variant}__cycle-${String(cycle).padStart(2, "0")}`,
          provider,
          model,
          profile: "production_comedy",
          variant,
          title: "Production comedy script",
          script: output.script,
          metrics: { candidateCount: 1, passedCount: words >= 55 && words <= 85 ? 1 : 0, passRate: words >= 55 && words <= 85 ? 1 : 0, meanWords: words, meanSeconds: Math.ceil((words / 150) * 60) },
        });
      } catch (error) {
        candidates.push({ runId: `${variant}__cycle-${String(cycle).padStart(2, "0")}`, provider, model, profile: "production_comedy", variant, failed: error instanceof Error ? error.message : "Production generation failed." });
      }
    }
  }
  return { ...research, candidates };
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.help) {
    console.log("Usage: npm run evals:production -- --subject https://github.com/owner/repo [--cycles 3] [--directions baseline,one-premise,viewer-first] [--provider production|openai-compatible --base-url http://host:4000/v1 --model model-id --api-key-env ENV_VAR]");
    return;
  }
  const report = await runProductionComedyBaseline(options);
  const runDirectory = path.resolve(options.outputRoot, new Date().toISOString().replace(/[:.]/g, "-"));
  await mkdir(runDirectory, { recursive: true });
  await Promise.all([
    writeFile(path.join(runDirectory, "manifest.json"), `${JSON.stringify({ generatedAt: new Date().toISOString(), options, subject: { name: report.summary.name, url: report.summary.url }, researchMode: report.researchMode, researchWarning: report.researchWarning }, null, 2)}\n`),
    writeFile(path.join(runDirectory, "results.json"), `${JSON.stringify(report.candidates, null, 2)}\n`),
    writeFile(path.join(runDirectory, "blind-review.md"), productionBlindReviewMarkdown(report.candidates.filter((candidate) => !candidate.failed))),
    writeFile(path.join(runDirectory, "review.csv"), "run_id,packet_id,decision,rank,reason,notes,mechanics,tone,grounding\n"),
  ]);
  console.log(JSON.stringify({ runDirectory, candidateCount: report.candidates.length, generated: report.candidates.filter((candidate) => !candidate.failed).length, failed: report.candidates.filter((candidate) => candidate.failed).map((candidate) => ({ runId: candidate.runId, error: candidate.failed })) }, null, 2));
}

if (import.meta.url === `file://${process.argv[1]}`) main().catch((error) => { console.error(error.message); process.exitCode = 1; });
